//! 256 distinct functions and counters for report navigation and search to showcase a large
//! firmware.
use core::hint::black_box;
use core::sync::atomic::{AtomicU32, Ordering};

macro_rules! stages {
    ($(($name:ident, $seed:expr)),* $(,)?) => {
        $(mod $name {
            use super::*;
            pub static COUNTER: AtomicU32 = AtomicU32::new($seed);

            #[inline(never)]
            pub fn run(input: u32) -> u32 {
                // Only the main loop writes this counter. Load/store also works on RV32IMC.
                let previous = COUNTER.load(Ordering::Relaxed);
                COUNTER.store(previous.wrapping_add(1), Ordering::Relaxed);
                black_box(input).wrapping_add(previous)
                    .wrapping_mul(2 * $seed + 1).rotate_left($seed % 31 + 1)
            }
        })*

        #[no_mangle]
        pub static BARQ_LARGE_STAGES: [fn(u32) -> u32; 256] = [$($name::run),*];
    };
}

